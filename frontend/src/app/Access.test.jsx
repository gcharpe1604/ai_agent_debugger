import { describe, it, expect, vi } from 'vitest'
import { render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import App from '../test/FixtureApp.jsx'
import { fixtureRepository } from '../test/fixtureRepository.js'

const at = path => window.history.replaceState(null, '', '/#' + path)

describe('Milestone 4A access and projects', () => {
  it('validates forms, exposes password visibility and never simulates authentication success', async () => {
    at('/account/login'); const user = userEvent.setup(); render(<App/>)
    await user.click(screen.getByRole('button', { name: 'Sign in' }))
    expect(await screen.findByText('Enter your email address.')).toBeTruthy()
    expect(document.activeElement).toBe(screen.getByLabelText('Email'))
    await user.type(screen.getByLabelText('Email'), 'developer@example.com')
    await user.type(screen.getByLabelText('Password', { exact: true }), 'not-a-real-secret')
    await user.click(screen.getByRole('button', { name: 'Show password' }))
    expect(screen.getByLabelText('Password', { exact: true }).type).toBe('text')
    await user.click(screen.getByRole('button', { name: 'Sign in' }))
    expect(await screen.findByRole('alert')).toHaveProperty('textContent', expect.stringContaining('not connected'))
    expect(screen.getByLabelText('Password', { exact: true }).value).toBe('')
    expect(localStorage.length).toBe(0)
    expect(sessionStorage.getItem('password')).toBeNull()
    await user.click(screen.getByRole('link', { name: 'Register' }))
    expect(await screen.findByRole('heading', { name: 'Create an account' })).toBeTruthy()
    expect(screen.getByLabelText('Name', { exact: true })).toBeTruthy()
    expect(screen.queryByLabelText('Password', { exact: true })).toBeNull()
  })

  it('prevents duplicate submissions and keeps failures generic rather than echoing credentials', async () => {
    at('/account/login'); let reject
    const signIn = vi.fn(() => new Promise((_, fail) => { reject = fail }))
    const user = userEvent.setup(); render(<App accountAdapter={{ signIn }}/>)
    await user.type(screen.getByLabelText('Email'), 'dev@example.com')
    await user.type(screen.getByLabelText('Password', { exact: true }), 'secret-example')
    await user.click(screen.getByRole('button', { name: 'Sign in' }))
    expect(screen.getByRole('button', { name: 'Signing in…' }).disabled).toBe(true)
    expect(screen.getByRole('button', { name: 'Show password' }).disabled).toBe(true)
    reject(new Error('secret-example'))
    expect(await screen.findByRole('alert')).toHaveProperty('textContent', expect.stringContaining('Could not sign in'))
    expect(screen.getByRole('alert').textContent).not.toContain('secret-example')
  })

  it('does not turn a fulfilled registration call into automatic sign-in or trust its response as access', async () => {
    at('/account/register'); const user = userEvent.setup()
    const register = vi.fn(async () => ({ token: 'must-not-persist', authorized: true }))
    render(<App accountAdapter={{ register }}/> )
    expect(document.title).toContain('Step 1 of 2')
    expect(screen.getByRole('list', { name: 'Registration steps' }).querySelector('[aria-current="step"]').textContent).toContain('Your details')
    await user.click(screen.getByRole('button', { name: 'Continue', exact: true }))
    expect(document.activeElement).toBe(screen.getByLabelText('Name', { exact: true }))
    await user.type(screen.getByLabelText('Name', { exact: true }), 'Dev Example')
    await user.type(screen.getByLabelText('Email'), 'dev@example.com')
    await user.click(screen.getByRole('button', { name: 'Continue', exact: true }))
    expect(document.activeElement).toBe(screen.getByLabelText('Username', { exact: true }))
    expect(document.title).toContain('Step 2 of 2')
    expect(screen.getByText('dev@example.com')).toBeTruthy()
    expect(screen.getByRole('list', { name: 'Registration steps' }).querySelector('[aria-current="step"]').textContent).toContain('Credentials')
    expect(register).not.toHaveBeenCalled()
    await user.type(screen.getByLabelText('Username', { exact: true }), 'dev-example')
    await user.type(screen.getByLabelText('Password', { exact: true }), 'example-only')
    await user.type(screen.getByLabelText('Confirm password', { exact: true }), 'different')
    await user.click(screen.getByRole('button', { name: 'Create account' }))
    expect(await screen.findByText('Passwords do not match.')).toBeTruthy()
    expect(register).not.toHaveBeenCalled()
    await user.clear(screen.getByLabelText('Confirm password', { exact: true }))
    await user.type(screen.getByLabelText('Confirm password', { exact: true }), 'example-only')
    await user.click(screen.getByRole('button', { name: 'Create account' }))
    expect(await screen.findByText('Accept the Terms and Conditions to continue.')).toBeTruthy()
    expect(register).not.toHaveBeenCalled()
    await user.click(screen.getByRole('checkbox', { name: 'I agree to the Terms and Conditions' }))
    await user.click(screen.getByRole('button', { name: 'Create account' }))
    expect(await screen.findByRole('alert')).toHaveProperty('textContent', expect.stringContaining('No signed-in session has been established'))
    expect(register).toHaveBeenCalledWith(expect.objectContaining({ name: 'Dev Example', email: 'dev@example.com', username: 'dev-example', password: 'example-only' }))
    expect(screen.getByLabelText('Password', { exact: true }).value).toBe('')
    expect(screen.getByLabelText('Confirm password', { exact: true }).value).toBe('')
    expect(screen.queryByRole('link', { name: 'Terms and Conditions' })).toBeNull()
    expect(window.location.hash).toBe('#/account/register')
    expect(localStorage.length).toBe(0)
  })

  it('keeps identity but clears passwords and agreement when going back in registration', async () => {
    at('/account/register'); const user = userEvent.setup(); render(<App/> )
    await user.type(screen.getByLabelText('Name', { exact: true }), 'Dev Example')
    await user.type(screen.getByLabelText('Email'), 'dev@example.com')
    await user.click(screen.getByRole('button', { name: 'Continue', exact: true }))
    await user.type(screen.getByLabelText('Username', { exact: true }), 'dev-example')
    await user.type(screen.getByLabelText('Password', { exact: true }), 'preview-only')
    await user.type(screen.getByLabelText('Confirm password', { exact: true }), 'preview-only')
    await user.click(screen.getByRole('button', { name: 'Show confirm password' }))
    expect(screen.getByLabelText('Confirm password', { exact: true }).type).toBe('text')
    await user.click(screen.getByRole('checkbox', { name: 'I agree to the Terms and Conditions' }))
    await user.click(screen.getByRole('button', { name: 'Back', exact: true }))
    expect(screen.getByLabelText('Name', { exact: true }).value).toBe('Dev Example')
    expect(screen.getByLabelText('Email').value).toBe('dev@example.com')
    await user.click(screen.getByRole('button', { name: 'Continue', exact: true }))
    expect(screen.getByLabelText('Username', { exact: true }).value).toBe('dev-example')
    expect(screen.getByLabelText('Password', { exact: true }).value).toBe('')
    expect(screen.getByLabelText('Confirm password', { exact: true }).value).toBe('')
    expect(screen.getByLabelText('Confirm password', { exact: true }).type).toBe('password')
    expect(screen.getByRole('checkbox', { name: 'I agree to the Terms and Conditions' }).checked).toBe(false)
  })

  it('shows expired and denied states without blocking the sample debugger or allowing an external return', async () => {
    at('/account/session-expired?returnTo=https%3A%2F%2Fevil.example'); const user = userEvent.setup(); render(<App/>)
    expect(await screen.findByRole('heading', { name: 'Session expired' })).toBeTruthy()
    await user.click(screen.getByRole('link', { name: 'Sign in' }))
    expect(window.location.hash).not.toContain('evil')
    await user.click(screen.getByRole('link', { name: 'Back to projects' }))
    await user.click(await screen.findByRole('link', { name: /^Agent examples/ }))
    await screen.findByRole('link', { name: 'refund-policy-review R-1042' })
    window.location.hash = '/account/access-denied'
    expect(await screen.findByRole('heading', { name: 'Access denied' })).toBeTruthy()
    expect(screen.queryByText('refund-policy-review')).toBeNull()
  })

  it('creates an explicitly local project from zero projects and opens an empty scoped explorer', async () => {
    const user = userEvent.setup(); render(<App repository={{ ...fixtureRepository, projects: [] }}/>)
    await user.click(await screen.findByRole('link', { name: 'Create project' }))
    expect(screen.getByText(/Project changes reset on reload/)).toBeTruthy()
    await user.click(screen.getByRole('button', { name: 'Create project' }))
    expect(await screen.findByText('Enter a project name.')).toBeTruthy()
    await user.type(screen.getByLabelText('Project name'), 'Research lab')
    await user.click(screen.getByRole('button', { name: 'Create project' }))
    await screen.findByRole('heading', { name: 'No traces yet' })
    expect(screen.getByLabelText('Project').selectedOptions[0].textContent).toBe('Research lab')
    expect(screen.queryByText('Sample data')).toBeNull()
    expect(localStorage.getItem('projects')).toBeNull()
  })

  it('saves basic project identity and discards incompatible trace/query selection on switching projects', async () => {
    at('/projects/agent-examples/settings'); const user = userEvent.setup(); render(<App/>)
    await user.clear(await screen.findByLabelText('Project name'))
    await user.type(screen.getByLabelText('Project name'), 'Agent workshop')
    await user.click(screen.getByRole('button', { name: 'Save changes' }))
    expect(await screen.findByRole('status')).toHaveProperty('textContent', expect.stringContaining('Saved'))
    window.location.hash = '/projects/agent-examples/runs/R-1042?span=compose&view=timeline'
    await screen.findByRole('tree', { name: 'Execution spans' })
    await user.selectOptions(screen.getByLabelText('Project'), 'sandbox')
    await screen.findByRole('link', { name: 'sandbox-policy-check R-2042' })
    expect(window.location.hash).toBe('#/projects/sandbox/runs')
    expect(screen.queryByRole('tree')).toBeNull()
  })

  it.each([['forbidden', 'Access denied'], ['expired', 'Session expired'], ['failure', 'Could not load projects']])('distinguishes %s project reads', async (kind, title) => {
    at('/projects')
    render(<App projectAdapter={{ mode: 'fixture', listProjects: async () => { throw Object.assign(new Error('private detail'), { kind }) } }}/>)
    expect(await screen.findByRole('heading', { name: title })).toBeTruthy()
    expect(document.body.textContent).not.toContain('private detail')
  })

  it('does not render a late project read from an obsolete adapter', async () => {
    at('/projects'); let release
    const late = { mode: 'fixture', listProjects: () => new Promise(resolve => { release = resolve }) }
    const { rerender } = render(<App projectAdapter={late}/> )
    expect(screen.getByRole('status').textContent).toContain('Loading projects')
    rerender(<App projectAdapter={{ mode: 'fixture', listProjects: async () => [] }}/>)
    await screen.findByRole('heading', { name: 'Create your first project' })
    release([{ id: 'stale', name: 'Stale private project' }])
    await waitFor(() => expect(screen.queryByText('Stale private project')).toBeNull())
  })

  it('keeps a valid project name editable after a request failure and allows retry', async () => {
    at('/projects/agent-examples/settings')
    const updateProject = vi.fn().mockRejectedValueOnce(new Error('private transport details')).mockImplementation(async ({ projectId, name }) => ({ id: projectId, name }))
    const user = userEvent.setup()
    render(<App projectAdapter={{ mode: 'fixture', listProjects: async () => fixtureRepository.projects, updateProject }}/>)
    const name = await screen.findByLabelText('Project name')
    await user.clear(name); await user.type(name, 'Trace review')
    await user.click(screen.getByRole('button', { name: 'Save changes' }))
    expect(await screen.findByRole('alert')).toHaveProperty('textContent', expect.stringContaining('Could not save changes'))
    expect(name.getAttribute('aria-invalid')).toBe('false')
    expect(name.value).toBe('Trace review')
    expect(document.body.textContent).not.toContain('private transport details')
    await user.click(screen.getByRole('button', { name: 'Save changes' }))
    expect(await screen.findByRole('status')).toHaveProperty('textContent', expect.stringContaining('Saved'))
    expect(screen.queryByRole('alert')).toBeNull()
  })

  it('cancels pending account submission and drops credentials when changing forms', async () => {
    at('/account/login'); let signal, release
    const signIn = vi.fn(args => { signal = args.signal; return new Promise(resolve => { release = resolve }) })
    const user = userEvent.setup(); render(<App accountAdapter={{ signIn }}/>)
    await user.type(screen.getByLabelText('Email'), 'dev@example.com')
    await user.type(screen.getByLabelText('Password', { exact: true }), 'fixture-only')
    await user.click(screen.getByRole('button', { name: 'Sign in' }))
    await user.click(screen.getByRole('link', { name: 'Register' }))
    await screen.findByRole('heading', { name: 'Create an account' })
    expect(signal.aborted).toBe(true)
    expect(screen.queryByLabelText('Password', { exact: true })).toBeNull()
    release({ authorized: true })
    await waitFor(() => expect(screen.queryByRole('alert')).toBeNull())
    expect(window.location.hash).toContain('/account/register')
  })
})
